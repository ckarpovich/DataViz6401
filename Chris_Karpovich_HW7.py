import streamlit as st
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
import streamlit.components.v1 as components
from sklearn.decomposition import TruncatedSVD
from sklearn.feature_extraction.text import CountVectorizer, TfidfVectorizer
from bertopic import BERTopic
import umap
import plotly.express as px

@st.cache_resource
def create_topic_model(docs):
    topic_model = BERTopic(verbose=False)
    topics, probs = topic_model.fit_transform(docs)
    return topic_model, topics, probs

@st.cache_data
def create_projection(emb):
    xy = umap.UMAP(n_components=2, random_state=8).fit_transform(emb)
    return xy

st.header("Text Message Spam Analysis")

df = pd.read_csv("SMSSpamCollection", sep = "\t", names = ["label", "message"])
spam = df[df["label"] == "spam"].copy()

#Honest Frequency
st.subheader("Most Frequent Words in Spam Text Messages")

docs = spam["message"].astype(str)

fig, ax = plt.subplots()
cv = CountVectorizer(stop_words="english", max_features=20)
counts = cv.fit_transform(docs)
freq = pd.Series(counts.sum(axis=0).A1, index=cv.get_feature_names_out())

freq.sort_values().plot.barh()
st.pyplot(fig)

st.caption("This chart shows the 20 most frequent words that appear in the spam messages from this dataset.  It does not count common English stop words (a, the, and, etc.).  This can be misleading as frequency does not reveal meaning or context.  Since I only used spam messages, we cannot use this to distinguish from real messages.")

#Topic Model Visualization
st.subheader("Spam Text Message Topic Modeling")

topic_model, topics, probs = create_topic_model(docs.tolist())
st.dataframe(topic_model.get_topic_info().head())

fig = topic_model.visualize_topics()

fig.update_xaxes(autorange = True)
fig.update_yaxes(autorange = True)
fig.update_layout(title_font = dict(color = "red"))
st.plotly_chart(fig)

st.caption("Each circle represents a topic generated by the model based on similarities in the message text.  The size represents how many messages belong to that particular topic.  This can help reveal any underlying patterns within spam messages." \
" It could be misleading and hard to comprehend as the topics are generated by the model.  Some topics also overlap heavily, which is not a problem, but may be hard to understand when looking at the chart.")

#Embedding Projection
st.subheader("Spam Text Message Embedded Projection")
emb = topic_model.embedding_model.embed(docs.tolist())
xy = create_projection(emb.tolist())

plot = pd.DataFrame({
    "UMAP Dimension 1": xy[:, 0],
    "UMAP Dimension 2": xy[:, 1],
    "Topic": topics,
    "Message": docs.tolist()
})


fig = px.scatter(
    plot,
    x = "UMAP Dimension 1",
    y = "UMAP Dimension 2",
    color = "Topic",
    hover_data = ["Message"],
    title = "Spam Embedding Projection"
)

st.plotly_chart(fig)

st.caption("The scatterplot represents each individual spam message as a point.  Similar messages are generally closer together.  The colors represent the topic assigned by BERTopic.  Hovering over a point lets you see the message and understand why messages may be closer or farther from each other." \
" This can be misleading because the axes do not have interpretable meanings, and points that appear together may be missing context and not have the same meaning.")